import assert from 'node:assert/strict';
import {marketOffers,jihadOffers,catalogPage,offerStatus,captureIntent,revalidateIntent} from '../../src/ui/views/shop-catalog.js';
const fixtures=Array.from({length:11},(_,i)=>Object.freeze({key:'post:'+i,kind:i>6?'sh':'pl',id:i>6?'h'+i:null,qty:5,cur:'sol',price:6000,lim:3}));
const input=Object.freeze(fixtures);
const rows=marketOffers(input, it=>it.key==='post:1'?0:3,()=>6000);
assert.equal(rows.length,11);
assert.equal(offerStatus(rows[0]),'ready');
assert.equal(offerStatus(rows[1]),'sold');
assert.equal(offerStatus({...rows[0],balance:5999}),'funds');
assert.equal(offerStatus({...rows[0],left:-2}),'unavailable');
assert.equal(offerStatus(null),'unavailable');
assert.equal(catalogPage(rows,{page:7}).index,1);
assert.equal(catalogPage(rows,{page:1}).visible.length,5);
assert.equal(catalogPage(rows,{filter:'shards'}).count,4);
assert.equal(catalogPage(rows,{filter:'shards',selected:'post:0'}).selected,'post:7');
assert.equal(catalogPage([]).selected,null);
const intent=captureIntent(rows[0],'post:2026-11-26');
assert.ok(Object.isFrozen(intent));
assert.equal(revalidateIntent(intent,rows,'post:2026-11-26'),rows[0]);
assert.equal(revalidateIntent(intent,rows,'post:2026-11-27'),null);
assert.equal(revalidateIntent(intent,[],intent.epoch),null);
for(const patch of [{price:1},{qty:4},{left:0},{balance:0},{route:'fbuy'},{id:'different'}])assert.equal(revalidateIntent(intent,[{...rows[0],...patch}],intent.epoch),null);
const j=jihadOffers([{key:'med3',n:'Аптечки',ico:'med',price:80,buy(){throw Error('must not execute');}},{key:'d:one',ico:'disk',price:220,lim:1,sold:true}],80);
assert.equal(j[0].qty,3);assert.equal(j[0].route,'cqjbuy');assert.equal(j[0].left,-1);assert.equal(offerStatus(j[1]),'sold');assert.ok(!('buy' in j[0]));
console.log('shop catalog: read-only projection, stable selection and stale intent checks passed');
