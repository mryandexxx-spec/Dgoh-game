import assert from 'node:assert/strict';
import { FX } from '../src/data/fx.js';
import { canApplyStatus, consumeForesight, markHouseVictim, markedDamageFactor, mayRevive, strongestAlly, orderedAssist } from '../src/logic/battle/baron-mechanics.js';
import { applyFx, hit } from '../src/logic/battle/engine.js';
assert.equal(FX.isolation.bad,true);
assert.equal(FX.foresight.bad,undefined);
assert.equal(FX.debuffImmune.bad,undefined);
const caster={uid:'a',side:'A',alive:true,def:{id:'baron_legend',sn:'Барон',f:['hark']},pot:1};
const ally={uid:'b',side:'A',alive:true,def:{id:'feyd',sn:'Фейд',f:['hark'],basic:{dt:'blade',m:1.1}},dmg:200,idx:1,fx:{isolation:2},hp:100,maxHp:100};
const enemy={uid:'c',side:'B',alive:true,def:{id:'leto',sn:'Лето',f:['atr']},dmg:400,idx:0,fx:{foresight:1},hp:1000,maxHp:1000,maxShield:0,shield:0,arm:0,eva:0,crit:0,ten:0};
const B={units:[caster,ally,enemy],events:[],log:[],over:null,rng:()=>.5,leader:{A:null,B:null}};
assert.equal(canApplyStatus(ally,caster,false),false);
assert.equal(canApplyStatus(ally,ally,false),true);
applyFx(B,caster,ally,'attackUp',2);
assert.equal(ally.fx.attackUp,undefined);
applyFx(B,ally,ally,'attackUp',2);
assert.equal(ally.fx.attackUp,2);
enemy.fx.debuffImmune=2;
assert.equal(canApplyStatus(enemy,caster,true),false);
applyFx(B,caster,enemy,'horror',2);
assert.equal(enemy.fx.horror,undefined);
delete enemy.fx.debuffImmune;
assert.equal(consumeForesight(enemy,'blade'),true);
assert.equal(enemy.fx.foresight,undefined);
enemy.fx.foresight=1;
assert.equal(consumeForesight(enemy,'voice'),false);
assert.equal(enemy.fx.foresight,1);
assert.equal(markHouseVictim(B.units,'A'),enemy);
assert.equal(markedDamageFactor(enemy,ally),1.25);
assert.equal(markedDamageFactor(enemy,caster,.1),1.1);
assert.equal(markedDamageFactor(ally,caster),1);
assert.equal(strongestAlly(B.units,caster),ally);
const shots=[];
assert.equal(orderedAssist(B,caster,enemy,ally,1.5,(b,h,t,dt,m)=>{shots.push([h.uid,t.uid,dt,m]);return true;}),true);
assert.deepEqual(shots,[['b','c','blade',1.65]]);
assert.equal(orderedAssist(B,caster,enemy,caster,1.5,()=>true),false);
enemy.noRev=true;
assert.equal(mayRevive(enemy),false);
delete enemy.noRev;
assert.equal(mayRevive(enemy),true);
// Real hit: foresight consumes without a damage roll; voice bypasses foresight.
caster.dmg=100;caster.fx={};caster.crit=0;caster.eva=0;
ally.fx={};enemy.fx={foresight:1};enemy.houseVictimSide='A';enemy.shield=0;
assert.equal(hit(B,caster,enemy,'blade',1),false);
assert.equal(enemy.hp,1000);
assert.equal(enemy.fx.foresight,undefined);
enemy.fx.foresight=1;
hit(B,caster,enemy,'voice',1);
assert.ok(enemy.hp<1000);
assert.equal(enemy.fx.foresight,1);
console.log('BH2 isolation, foresight, House mark, assisted attacks: PASS');
